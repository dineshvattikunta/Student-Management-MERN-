export const seedDatabase = async () => {
  try {
    const studentCount = await Student.countDocuments();
    if (studentCount > 0) {
      console.log(`ℹ️ Database already contains ${studentCount} students. Skipping auto-seed.`);
      return;
    }

    console.log('🌱 Seeding CampusOS database with realistic initial data...');

    await Promise.all([
      Department.deleteMany({}),
      Course.deleteMany({}),
      Student.deleteMany({}),
    ]);

    await Department.insertMany(initialDepartments);
    await Course.insertMany(initialCourses);
    await Student.insertMany(initialStudents);

    console.log(`✨ Successfully seeded:
- ${initialDepartments.length} Departments
- ${initialCourses.length} Courses
- ${initialStudents.length} Students`);
  } catch (error) {
    console.error('❌ Seeding failed:', error);
  }
};
